function results = test_imtBandDefaultParams()
%TEST_IMTBANDDEFAULTPARAMS Unit tests for the 2.7 GHz band parameter layer.
%
%   RESULTS = test_imtBandDefaultParams()
%
%   Covers imtBandName, imtBandDefaultParams, the itu_2p7ghz_4x8 geometry
%   preset, and the 2.7 GHz r23ScenarioPreset entries. No Monte Carlo runs.
%       T1.  '7ghz' returns r23DefaultParams unchanged (isequal), for the
%            default call, 'urban', and 'suburban'.
%       T2.  2.7 GHz urban: ITU 4x8 antenna table, 2750 MHz / 100 MHz,
%            Part 27 power (85 dBm = 65 dBm/MHz + 20 dB), conducted + gain
%            == EIRP, ITU 2-3 GHz BS height 20 m / radius 400 m.
%       T3.  2.7 GHz suburban: 25 m / 800 m, same antenna and power.
%       T4.  Only bsHeight_m / cellRadius_m / interSiteDistance_m differ
%            from r23DefaultParams in the deployment block; TDD activity
%            and network loading unchanged.
%       T5.  Unsupported environment and unknown band raise errors.
%       T6.  imtBandName aliases.
%       T7.  aasGeometryPreset('itu_2p7ghz_4x8'): 26.22 dBi, 192 elements,
%            85 dBm, conducted + gain == EIRP; aliases; agrees with the
%            nested params antenna table.
%       T8.  r23ScenarioPreset 2p7ghz-urban / 2p7ghz-suburban values.
%
%   Returns struct with .passed (logical) and .summary (cellstr).

    results.summary = {};
    results.passed  = true;
    tol = 1e-9;

    % ---- T1 -----------------------------------------------------------
    ok1 = isequal(imtBandDefaultParams('7ghz'), r23DefaultParams()) && ...
          isequal(imtBandDefaultParams('7ghz', 'urban'), r23DefaultParams('urban')) && ...
          isequal(imtBandDefaultParams('7ghz', 'suburban'), r23DefaultParams('suburban')) && ...
          isequal(imtBandDefaultParams(), r23DefaultParams());
    results = check(results, ok1, 'T1: ''7ghz'' == r23DefaultParams (isequal)');

    % ---- T2 -----------------------------------------------------------
    pu = imtBandDefaultParams('2p7ghz', 'urban');
    expGain = 6.4 + 10*log10(3) + 10*log10(32);
    ok2 = pu.aas.numRows == 4 && pu.aas.numColumns == 8 && ...
          pu.aas.numElementRowsInSubarray == 3 && ...
          pu.aas.horizontalSpacing_lambda == 0.5 && ...
          pu.aas.verticalSubarraySpacing_lambda == 2.1 && ...
          pu.aas.verticalElementSeparationInSubarray_lambda == 0.7 && ...
          pu.aas.subarrayDowntilt_deg == 3 && ...
          pu.aas.mechanicalDowntilt_deg == 6 && ...
          pu.aas.elementGain_dBi == 6.4 && ...
          pu.bs.frequency_MHz == 2750 && ...
          isequal(pu.bs.frequencyRange_MHz, [2700 2800]) && ...
          strcmp(pu.bs.duplex, 'TDD') && ...
          pu.bs.channelBandwidth_MHz == 100 && ...
          abs(pu.bs.maxEirpPerSector_dBm - 85) <= tol && ...
          pu.bs.eirpDensityLimit_dBmPerMHz == 65 && ...
          abs(pu.bs.peakGain_dBi - expGain) <= tol && ...
          abs(pu.bs.peakGain_dBi - 26.22) <= 0.01 && ...
          abs(pu.bs.conductedPower_dBm + pu.bs.peakGain_dBi - pu.bs.maxEirpPerSector_dBm) <= tol && ...
          abs(pu.bs.conductedPower_dBm - 58.78) <= 0.01 && ...
          abs(pu.aas.conductedPowerPerSubarrayBeforeOhmic_dBm - 40.72) <= 0.01 && ...
          pu.deployment.bsHeight_m == 20 && ...
          pu.deployment.cellRadius_m == 400 && ...
          abs(pu.deployment.interSiteDistance_m - sqrt(3)*400) <= tol && ...
          strcmp(pu.deployment.environment, 'urban') && ...
          strcmp(pu.metadata.band, '2p7ghz') && ...
          contains(pu.metadata.powerBasis, 'Part 27');
    results = check(results, ok2, sprintf( ...
        'T2: 2.7 GHz urban params (gain %.3f dBi, conducted %.3f dBm, EIRP %.3f dBm)', ...
        pu.bs.peakGain_dBi, pu.bs.conductedPower_dBm, pu.bs.maxEirpPerSector_dBm));

    % ---- T3 -----------------------------------------------------------
    ps = imtBandDefaultParams('2p7ghz', 'suburban');
    ok3 = ps.deployment.bsHeight_m == 25 && ps.deployment.cellRadius_m == 800 && ...
          abs(ps.deployment.interSiteDistance_m - sqrt(3)*800) <= tol && ...
          strcmp(ps.deployment.environment, 'suburban') && ...
          isequal(ps.aas, pu.aas) && isequal(ps.bs, pu.bs);
    results = check(results, ok3, 'T3: 2.7 GHz suburban 25 m / 800 m; antenna and power match urban');

    % ---- T4 -----------------------------------------------------------
    ok4 = true;
    envs = {'urban', 'suburban'};
    for e = 1:numel(envs)
        p7 = r23DefaultParams(envs{e});
        p2 = imtBandDefaultParams('2p7ghz', envs{e});
        d7 = rmfield(p7.deployment, {'bsHeight_m', 'cellRadius_m', 'interSiteDistance_m'});
        d2 = rmfield(p2.deployment, {'bsHeight_m', 'cellRadius_m', 'interSiteDistance_m'});
        ok4 = ok4 && isequal(d7, d2) && isequal(p7.ue, p2.ue) && isequal(p7.sim, p2.sim) && ...
              p2.bs.tddActivityFactor == p7.bs.tddActivityFactor && ...
              p2.bs.networkLoadingFactor == p7.bs.networkLoadingFactor;
    end
    results = check(results, ok4, ...
        'T4: only height / radius / ISD change in deployment; ue, sim, TDD, loading inherited');

    % ---- T5 -----------------------------------------------------------
    ok5 = throwsId(@() imtBandDefaultParams('2p7ghz', 'micro'), ...
                   'imtBandDefaultParams:unsupportedEnvironment') && ...
          throwsId(@() imtBandDefaultParams('5ghz'), 'imtBandName:unknownBand') && ...
          throwsId(@() imtBandName(struct()), 'imtBandName:badBand');
    results = check(results, ok5, 'T5: unsupported environment / unknown band raise errors');

    % ---- T6 -----------------------------------------------------------
    a2 = {'2p7ghz', '2.7GHz', '2.7 GHz', '2700-2800MHz', '2750', "2p7ghz"};
    a7 = {'7ghz', '7GHz', 'r23', '8ghz', '7.125-8.4GHz'};
    ok6 = all(cellfun(@(b) strcmp(imtBandName(b), '2p7ghz'), a2)) && ...
          all(cellfun(@(b) strcmp(imtBandName(b), '7ghz'), a7)) && ...
          strcmp(imtBandName(2750), '2p7ghz');
    results = check(results, ok6, 'T6: imtBandName aliases resolve');

    % ---- T7 -----------------------------------------------------------
    g = aasGeometryPreset('itu_2p7ghz_4x8');
    gA = aasGeometryPreset('2p7ghz');
    ok7 = strcmp(g.presetName, 'itu_2p7ghz_4x8') && strcmp(gA.presetName, 'itu_2p7ghz_4x8') && ...
          abs(g.calculatedAntennaGainDbi - 26.22) <= 0.01 && ...
          abs(g.calculatedAntennaGainDbi - expGain) <= tol && ...
          g.totalPhysicalElementsAcrossPolarizations == 192 && ...
          abs(g.sectorEirpDbm - 85) <= tol && ...
          abs(g.conductedPowerDbm + g.calculatedAntennaGainDbi - g.sectorEirpDbm) <= tol && ...
          g.arrayRows == pu.aas.numRows && g.arrayCols == pu.aas.numColumns && ...
          g.subarrayElementRows == pu.aas.numElementRowsInSubarray && ...
          g.radiatingSubarrayVerticalSpacingLambda == pu.aas.verticalSubarraySpacing_lambda && ...
          g.mechanicalDowntiltDeg == pu.aas.mechanicalDowntilt_deg && ...
          abs(g.conductedPowerDbm - pu.bs.conductedPower_dBm) <= tol;
    results = check(results, ok7, sprintf( ...
        'T7: itu_2p7ghz_4x8 preset (%.3f dBi, %d elements) matches nested params', ...
        g.calculatedAntennaGainDbi, g.totalPhysicalElementsAcrossPolarizations));

    % ---- T8 -----------------------------------------------------------
    su = r23ScenarioPreset('2p7ghz-urban');
    ss = r23ScenarioPreset('2p7ghz-suburban');
    ok8 = strcmp(su.metadata.scenarioPreset, '2p7ghz-urban') && ...
          strcmp(su.metadata.band, '2p7ghz') && ...
          su.deployment.bsHeight_m == 20 && su.deployment.cellRadius_m == 400 && ...
          abs(su.bs.maxEirpPerSector_dBm - 85) <= tol && ...
          su.bs.frequency_MHz == 2750 && su.aas.numRows == 4 && ...
          su.sim.randomSeed == 20261101 && ...
          strcmp(ss.metadata.scenarioPreset, '2p7ghz-suburban') && ...
          ss.deployment.bsHeight_m == 25 && ss.deployment.cellRadius_m == 800 && ...
          ss.sim.randomSeed == 20261102 && ...
          isequal(r23ScenarioPreset('urban-baseline'), r23ScenarioPreset('urban-baseline'));
    results = check(results, ok8, 'T8: r23ScenarioPreset 2p7ghz-urban / 2p7ghz-suburban');

    fprintf('\n--- test_imtBandDefaultParams summary ---\n');
    for k = 1:numel(results.summary)
        fprintf('  %s\n', results.summary{k});
    end
    fprintf('  %s\n', ifElse(results.passed, 'ALL TESTS PASSED', 'TESTS FAILED'));
end

% =====================================================================
function r = check(r, cond, msg)
    if cond
        r.summary{end+1} = ['PASS  ' msg];
    else
        r.summary{end+1} = ['FAIL  ' msg];
        r.passed = false;
    end
end

function s = ifElse(cond, a, b)
    if cond, s = a; else, s = b; end
end

function tf = throwsId(fn, id)
    tf = false;
    try
        fn();
    catch err
        tf = strcmp(err.identifier, id);
    end
end
